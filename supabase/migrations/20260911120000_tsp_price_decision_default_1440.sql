-- ЧТО. tsp_config.price_decision_after_minutes: дефолт колонки 1 → 1440 (сутки).
--
-- ЗАЧЕМ. Миграция 20260702200000_tsp_price_decision_timer завела колонку с
-- `default 1` и сама назвала это тестовым значением («ДЕФОЛТ 1 минута для теста»);
-- на боевое его не вернули. Следствие измерено живьём 11.09 при проверке ARS-687:
-- опубликованная партия уходила с маркет-борда через ~1 минуту, то есть путь
-- «комбинат покупает с борда» был непригоден по построению.
--
-- Активная строка конфига переведена на 1440 отдельно 11.09 (правка данных,
-- DECISIONS_LOG). Здесь закрывается ВТОРАЯ половина: дефолт колонки. Без него
-- любая новая строка tsp_config или свежая база снова получают 1 минуту.
--
-- ПОЧЕМУ ОТДЕЛЬНАЯ МИГРАЦИЯ, А НЕ ДЕПЛОЙ d02_tsp.sql. Канон (d02 §9.4) правится
-- в том же PR — но `deploy.py --files d02_tsp.sql` заново проиграл бы весь файл,
-- который с последней выкладки (2026-07-30, git 72e8523d) ушёл вперёд на 509
-- вставок / 77 удалений (PR #174, «⚠ 360 mutates live RPCs»). Радиус для смены
-- одного дефолта неприемлем, и TSP-ADAPTER-02 требует, чтобы после d-файлов
-- ложились adapter-миграции, иначе воскресает uuid-overload. Миграция + зеркало
-- в §9.4 — штатный приём этого репозитория (так же заведена и сама колонка).
--
-- ОБРАТИМОСТЬ: `alter column price_decision_after_minutes set default 1;`
-- Данные не трогаются: set default действует только на будущие вставки.
-- ============================================================================

alter table public.tsp_config
    alter column price_decision_after_minutes set default 1440;

comment on column public.tsp_config.price_decision_after_minutes is
    'Слайс C: через сколько минут непроданная партия (published/offering, matched_heads=0)
     переводится в awaiting_price_decision (экран снижения цены). Дефолт 1440 мин = сутки
     (D-PRICEREC-01, владелец 11.09) — в одном шаге с offer_window_hours/
     mpk_decision_window_hours. Было 1 мин: тестовое значение миграции 20260702200000.';
